export function sampleQuestions(count = ROUND_COUNT, random = Math.random) {
  if (!Number.isInteger(count) || count < 1 || count > QUESTION_BANK.length) {
    throw new RangeError(`count must be an integer between 1 and ${QUESTION_BANK.length}`);
  }

  const shuffled = [...QUESTION_BANK];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const randomValue = random();
    if (!Number.isFinite(randomValue) || randomValue < 0 || randomValue >= 1) {
      throw new RangeError("random() must return a number from 0 (inclusive) to 1 (exclusive)");
    }

    const swapIndex = Math.floor(randomValue * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }

  return shuffled.slice(0, count);
}
